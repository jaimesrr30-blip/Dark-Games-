import type { StageId } from "./stages";

export type NpcRole = "mision" | "tienda" | "garaje" | "historia" | "mascotas" | "guardian";

export interface GuardianInfo {
  keyId: string;
  priceCoins: number;
  difficulty: number; // escala la IA del partido de desafío (0.3-0.98 en las etapas terrestres, hasta 1.16 en los planetas)
  winLine: string;
  payLine: string;
  noMoneyLine: string;
  alreadyLine: string;
}

export interface NpcDef {
  id: string;
  name: string;
  stage: StageId;
  pos: [number, number];
  color: string;
  role: NpcRole;
  shopId?: string;
  dialogue: string[];
  missionIds?: string[];
  guardian?: GuardianInfo;
  // Los NPCs de los mundos de espacio profundo (donde se puede morir) llevan
  // traje espacial: se dibujan con un casco/burbuja translúcida encima.
  suited?: boolean;
}

function guardian(keyId: string, priceCoins: number, difficulty: number, flavor?: Partial<GuardianInfo>): GuardianInfo {
  return {
    keyId,
    priceCoins,
    difficulty,
    winLine: flavor?.winLine ?? "¡Bien jugado! Un trato es un trato. Aquí tienes la llave.",
    payLine: flavor?.payLine ?? "Trato hecho. ¡Que empiece el partido!",
    noMoneyLine: flavor?.noMoneyLine ?? "No tienes suficiente. Vuelve cuando reúnas más monedas.",
    alreadyLine: flavor?.alreadyLine ?? "Ya tienes mi llave. ¡Buena suerte con las otras!",
  };
}

